// Claude-drevne generatorer på VSL-sidene. Sender skjemaet til /api/claude og viser resultatet.
(function () {
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  function list(items) {
    return "<ul class=\"check\">" + items.map(function (i) { return "<li>" + esc(i) + "</li>"; }).join("") + "</ul>";
  }

  var RENDER = {
    hooks: function (r) {
      return "<h3>Your positioning</h3><p class=\"lead\">" + esc(r.positioning) + "</p>" +
        "<h3>5 hooks for your first videos</h3>" + list(r.hooks) +
        "<h3>3 video ideas</h3>" + r.ideas.map(function (i) {
          return "<div class=\"card\" style=\"margin:10px 0\"><strong>" + esc(i.title) + "</strong><p>" + esc(i.outline) + "</p></div>";
        }).join("");
    },
    "build-plan": function (r) {
      return "<h3>" + esc(r.name) + "</h3><p class=\"lead\">" + esc(r.summary) + "</p>" +
        "<div class=\"stats\" style=\"grid-template-columns:1fr\"><div class=\"stat\"><b>~" + esc(r.estimate_days) + " build days</b><span>with Claude Code and a reviewing engineer</span></div></div>" +
        "<h3 style=\"margin-top:24px\">Components</h3>" + list(r.components) +
        "<h3>Build Day 1</h3>" + list(r.day1) +
        "<h3>Build Day 2</h3>" + list(r.day2) +
        "<h3>Risks to plan for</h3>" + list(r.risks);
    },
    healthspan: function (r) {
      var warn = r.see_physician
        ? "<div class=\"card\" style=\"border-color:#e58b8b;margin:16px 0\"><strong>Check with a physician first.</strong><p>" + esc(r.physician_note) + "</p></div>"
        : "";
      return "<h3>Your snapshot</h3><p class=\"lead\">" + esc(r.summary) + "</p>" + warn +
        "<h3>What matters most for you</h3>" + r.focus.map(function (f) {
          return "<div class=\"card\" style=\"margin:10px 0\"><strong>" + esc(f.area) + "</strong><p>" + esc(f.why) + "</p></div>";
        }).join("") +
        "<h3>Your first 14 days</h3>" + list(r.first_steps) +
        "<p class=\"fine\">General fitness guidance, not medical advice. Generated by AI; a coach and physician review everything for members.</p>";
    },
  };

  document.querySelectorAll("form[data-ai]").forEach(function (form) {
    var tool = form.getAttribute("data-ai");
    var out = document.querySelector('[data-ai-out="' + tool + '"]');
    var err = form.querySelector(".err");
    var btn = form.querySelector("[type=submit]");
    var label = btn.textContent;
    form.addEventListener("submit", function (e) {
      e.preventDefault();
      err.textContent = "";
      var data = Object.fromEntries(new FormData(form).entries());
      data.tool = tool;
      data.page = location.pathname;
      btn.disabled = true;
      btn.textContent = "Thinking…";
      out.innerHTML = "<p class=\"fine\">Working on it, this usually takes 10–30 seconds…</p>";
      fetch("/api/claude", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(data) })
        .then(function (r) { return r.json().catch(function () { return {}; }).then(function (j) { return { ok: r.ok, j: j }; }); })
        .then(function (res) {
          if (!res.ok) throw new Error(res.j.error || "Something went wrong.");
          out.innerHTML = "<div class=\"apply ai-result\">" + RENDER[tool](res.j.result) +
            "<p style=\"margin-top:24px\"><a class=\"btn\" href=\"#apply\">" + esc(form.getAttribute("data-cta") || "See if you qualify →") + "</a></p></div>";
          out.scrollIntoView({ behavior: "smooth", block: "start" });
        })
        .catch(function (x) { out.innerHTML = ""; err.textContent = x.message; })
        .finally(function () { btn.disabled = false; btn.textContent = label; });
    });
  });
})();
