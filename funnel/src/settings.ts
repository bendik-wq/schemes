const DEFS = new Map(SETTINGS.map((s) => [s.key, s]));

export function settingDef(key: string): SettingDef | undefined {
  return DEFS.get(key);
}

let cache: { at: number; rows: Map<string, string> } | null = null;
const TTL = 15_000;

export function clearSettingsCache() {
  cache = null;
}

async function dbRows(env: Env): Promise<Map<string, string>> {
  if (cache && Date.now() - cache.at < TTL) return cache.rows;
  const rows = new Map<string, string>();
  try {
    const r = await env.DB.prepare("SELECT key, value FROM settings").all<{ key: string; value: string }>();
    for (const row of r.results || []) rows.set(row.key, row.value);
  } catch { /* table may not exist yet during first migration */ }
  cache = { at: Date.now(), rows };
  return rows;
}

export interface Settings {
  get(key: string): string;
  bool(key: string): boolean;
  num(key: string, fallback?: number): number;
  has(key: string): boolean;
  source(key: string): "env" | "db" | "default" | "unset";
}

export async function loadSettings(env: Env): Promise<Settings> {
  const rows = await dbRows(env);
  const envVal = (k: string): string => {
    const v = env[k];
    return typeof v === "string" ? v.trim() : "";
  };
  const get = (k: string): string => envVal(k) || rows.get(k) || DEFS.get(k)?.def || "";
  // Learned scoring is opt-in: scoring.ts uses the table only while LEARNED_ROUTING is on.
  const learnedOn = ["1", "true", "yes", "on"].includes(get("LEARNED_ROUTING").toLowerCase());
  useLearnedPoints(learnedOn ? parseLearnedPoints(get("LEARNED_POINTS")) : null);
  return {
    get,
    bool: (k) => ["1", "true", "yes", "on"].includes(get(k).toLowerCase()),
    num: (k, fb = 0) => {
      const n = Number(get(k));
      return Number.isFinite(n) && get(k) !== "" ? n : fb;
    },
    has: (k) => get(k) !== "",
    source: (k) => (envVal(k) ? "env" : rows.has(k) && rows.get(k) ? "db" : DEFS.get(k)?.def ? "default" : "unset"),
  };
}

/** What the browser may see for a setting. Secrets: "set" or last 4 chars (only for 16+ chars). */
export function maskValue(def: SettingDef, value: string): string {
  if (!value) return "";
  if (!def.secret) return value;
  if (value.length >= 16) return "••••" + value.slice(-4);
  return "set";
}

export async function saveSetting(env: Env, key: string, value: string): Promise<void> {
  if (!DEFS.has(key)) throw new Error("unknown setting");
  const v = value.trim();
  if (v === "") await env.DB.prepare("DELETE FROM settings WHERE key = ?").bind(key).run();
  else
    await env.DB.prepare(
      "INSERT INTO settings (key, value, updated_at) VALUES (?, ?, ?) ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = excluded.updated_at",
    ).bind(key, v.slice(0, 4000), Date.now()).run();
  clearSettingsCache();
}
